        <h3>Licensing & DBPR Compliance</h3>
        <p>
          Smart Choice Contractors USA operates with a commitment to proper licensing, trade compliance, responsible business practices, and project documentation. Florida construction work may require certified or registered licenses depending on the trade, scope, and jurisdiction.
        </p>
        <ul>
          <li>Florida contractor license verification through DBPR.</li>
          <li>Trade-specific licensing for general, electrical, plumbing, roofing, HVAC, and related scopes when required.</li>
          <li>Permitting and inspection coordination when included in the written project scope.</li>
          <li>Compliance with applicable state, county, city, and local building department requirements.</li>
        </ul>

        <h3>Construction Contracts</h3>
        <p>
          Written agreements are critical for construction projects. A proper agreement should clearly define the scope of work, payment schedule, exclusions, allowances, responsibilities, change order process, schedule expectations, lien law notices, dispute resolution terms, and warranty provisions.
        </p>
        <p>
          Website descriptions, promotions, pricing examples, and marketing content are general information only. The final written estimate, proposal, invoice, change order, or contract controls the specific project.
        </p>

        <h3>Florida Construction Lien Law</h3>
        <p>
          Florida construction projects may be subject to Chapter 713, Florida Statutes. Contractors, subcontractors, sub-subcontractors, and material suppliers may have lien rights if they provide labor, services, or materials and are not paid according to applicable law.
        </p>
        <p>
          Owners should read contract notices carefully, request lien releases when appropriate, confirm payment procedures, and consult an attorney if they have questions about lien rights, Notice to Owner documents, final payment affidavits, or lien releases.
        </p>

        <h3>Notice of Commencement</h3>
        <p>
          A Notice of Commencement may be required for certain Florida permitted construction projects. The NOC identifies important project information and may need to be recorded with the county clerk and posted or submitted to the building department before inspections.
        </p>
        <p>
          Requirements vary based on project type, project value, jurisdiction, and Florida law. Customers should confirm requirements with the local building department, county clerk, or attorney before beginning permitted work.
        </p>

        <h3>Permits, Inspections & Florida Building Code</h3>
        <p>
          Many construction activities require permits and inspections, including structural changes, roofing, electrical work, plumbing work, mechanical work, additions, window and door replacements, floodplain work, and major renovations.
        </p>
        <p>
          Florida building departments may require drawings, engineering, product approvals, energy forms, flood documents, Notice of Commencement records, inspections, revisions, and final approvals before a project is complete.
        </p>

        <h3>Change Orders & Hidden Conditions</h3>
        <p>
          Construction projects can uncover hidden conditions such as damaged framing, unsafe wiring, plumbing defects, termite damage, rot, mold, flood damage, unpermitted work, code violations, or structural concerns. These conditions may require updated pricing, change orders, engineering, permits, or additional inspections.
        </p>

        <h3>Mediation, Arbitration & Dispute Resolution</h3>
        <p>
          Project documents may include dispute resolution processes such as communication escalation, mediation, arbitration, or court proceedings. The applicable written agreement controls how disputes are handled.
        </p>
        <p>
          Our goal is to resolve project concerns professionally through documentation, communication, inspections, written agreements, and fair review of the project facts.
        </p>

        <h3>Public Notarization of Documents</h3>
        <p>
          Certain Florida construction documents may require notarization, recording, owner signatures, contractor signatures, or official submission. Examples may include Notice of Commencement forms, permit documents, affidavits, lien releases, owner-builder documents, payment authorizations, or public records forms.
        </p>

        <h3>Cancellation Rights</h3>
        <p>
          Certain contracts may include cancellation rights under applicable Florida or federal law, depending on how and where the agreement was made, the type of transaction, and the nature of the service. Customers should review the written contract and any required cancellation notice carefully before signing.
        </p>

        <h3>Florida Homeowners’ Construction Recovery Fund</h3>
        <p>
          The Florida Construction Industry Recovery Fund may provide certain consumer protections in qualifying circumstances involving licensed contractors. Eligibility, claim requirements, limitations, and procedures are controlled by DBPR rules and Florida law.
        </p>

        <h3>Safety & OSHA Compliance</h3>
        <p>
          Safety is a core part of construction operations. Workers and subcontractors are expected to follow safe work practices, use appropriate PPE, maintain clean jobsites, protect customers and property, and comply with OSHA and project-specific safety requirements.
        </p>

        <h3>E-Verify Compliance</h3>
        <p>
          Florida law includes E-Verify requirements for certain employers, public agencies, contractors, subcontractors, and private employers meeting statutory thresholds. Smart Choice Contractors USA supports workforce compliance and lawful employment practices.
        </p>

