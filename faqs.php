          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do written contracts matter for construction projects?</summary>
          <div class="smart-faq-answer">
            <p>Yes. Written contracts help define scope of work, payment schedules, exclusions, warranties, change orders, responsibilities, and legal notices. A signed estimate or proposal may also become part of the project agreement.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What is a change order?</summary>
          <div class="smart-faq-answer">
            <p>A change order documents work that changes the original scope, price, materials, schedule, or project conditions. Change orders help avoid confusion and protect both the owner and contractor.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What is a lien release?</summary>
          <div class="smart-faq-answer">
            <p>A lien release is a document used to confirm that a contractor, subcontractor, or supplier has received payment or is releasing lien rights for a specific payment or project stage.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What is a Notice to Owner?</summary>
          <div class="smart-faq-answer">
            <p>A Notice to Owner is a Florida lien-law notice commonly used by subcontractors or suppliers who do not have a direct contract with the owner. It helps protect lien rights and informs the owner that labor or materials are being provided.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do you provide warranties?</summary>
          <div class="smart-faq-answer">
            <p>Warranty terms depend on the written agreement, manufacturer warranties, material warranties, trade scope, and project conditions. Warranty coverage should always be reviewed in writing before work begins.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Can project payments be made by credit card?</summary>
          <div class="smart-faq-answer">
            <p>Payment methods depend on the project and agreement. Some projects may allow credit card payments, ACH, checks, online payment links, or other approved methods. Fees or authorization forms may apply.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do subcontractors need insurance?</summary>
          <div class="smart-faq-answer">
            <p>Subcontractors should provide proper license information, insurance certificates, workers’ compensation documentation or exemptions where applicable, W-9 forms, and required agreements before performing work.</p>
