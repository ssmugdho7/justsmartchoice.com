        <h2>Permits, Codes & Florida Requirements</h2>
        <p>Helpful questions about permits, inspections, Florida Building Code, and county requirements.</p>
      </div>

      <div class="smart-faq-list">

        <details class="smart-faq-item">
          <summary>Do construction projects in Florida require permits?</summary>
          <div class="smart-faq-answer">
            <p>Many projects require permits, especially electrical, plumbing, roofing, structural, mechanical, additions, window and door replacements, and major remodeling. The final requirement depends on the local building department and exact project scope.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What Florida Building Code edition applies now?</summary>
          <div class="smart-faq-answer">
            <p>Florida currently uses the 8th Edition 2023 Florida Building Code for many current permit applications. Local jurisdictions may also have procedures, floodplain requirements, forms, and review requirements.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What is a Notice of Commencement?</summary>
          <div class="smart-faq-answer">
            <p>A Notice of Commencement is a Florida construction document related to lien law and permitted improvements. It identifies the property, owner, contractor, lender if applicable, and project start information. Some projects must record it before work or inspections.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>When is a Notice of Commencement required?</summary>
          <div class="smart-faq-answer">
            <p>Florida requirements depend on the project and statute. Florida law includes exceptions, including HVAC repair or replacement under $15,000 in certain direct contracts. Always confirm with the local building department or clerk before starting work.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Who records the Notice of Commencement?</summary>
          <div class="smart-faq-answer">
            <p>The property owner or authorized party typically records the NOC with the county clerk when required. Some jurisdictions also require the recorded copy to be uploaded to the permit portal before inspections.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do you handle inspections?</summary>
          <div class="smart-faq-answer">
            <p>When permit coordination is included in the project scope, we can help coordinate inspections. Inspection requirements depend on the permit, trade, project phase, and local building department.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do I need drawings for a remodeling permit?</summary>
          <div class="smart-faq-answer">
            <p>Many remodeling permits require drawings, especially when walls, structural framing, electrical layouts, plumbing layouts, mechanical systems, exterior changes, or life-safety conditions are involved.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Do flood zones affect remodeling work?</summary>
          <div class="smart-faq-answer">
            <p>Yes. Flood zones may trigger additional requirements, including substantial improvement or substantial damage review, FEMA-related documentation, elevation requirements, and special city or county review.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>What happens if hidden code issues are found during construction?</summary>
          <div class="smart-faq-answer">
            <p>Hidden issues such as unsafe wiring, damaged framing, plumbing defects, rot, termite damage, unpermitted work, or non-code conditions may require additional work, change orders, inspections, or engineering review.</p>
          </div>
        </details>

        <details class="smart-faq-item">
          <summary>Can I buy my own materials for a permitted project?</summary>
          <div class="smart-faq-answer">
            <p>Sometimes, but owner-supplied materials must meet project requirements, product approvals, code requirements, sizing, warranty requirements, and schedule needs. Incorrect materials can delay the project or increase labor cost.</p>
