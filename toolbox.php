        <p>Field rules for contractors, installers, helpers, subcontractors, and project managers working inside occupied homes or businesses.</p>
      </div>

      <div class="smart-toolbox-list-card">
        <ul class="smart-toolbox-rules">
          <li>Arrive on time or notify the customer and project manager before delays occur.</li>
          <li>Wear clean and professional clothing suitable for the project and customer environment.</li>
          <li>Protect floors, walls, cabinets, fixtures, countertops, furniture, and landscaping before work begins.</li>
          <li>Keep tools organized and maintain clear walking paths for customer safety.</li>
          <li>Do not enter private rooms, closets, garages, or storage areas unless the scope requires it and the customer approves access.</li>
          <li>Do not smoke, vape, drink alcohol, or use illegal substances on customer property.</li>
          <li>Do not use customer bathrooms, refrigerators, tools, ladders, materials, or equipment without permission.</li>
          <li>Do not play loud music, use offensive language, or argue on the jobsite.</li>
          <li>Keep the work area clean at the end of each workday.</li>
          <li>Take before, during, and after photos when required for documentation.</li>
          <li>Report hidden damage, unsafe wiring, plumbing leaks, rot, mold, termites, or structural concerns immediately.</li>
          <li>Never perform extra work without written approval, change order, or project manager confirmation.</li>
          <li>Follow Florida Building Code, NEC, plumbing code, manufacturer instructions, and permit conditions.</li>
          <li>Use proper PPE including eye protection, gloves, hearing protection, respirators, fall protection, and hard hats when required.</li>
          <li>Respect customer privacy, security cameras, pets, children, neighbors, and HOA rules.</li>
          <li>Secure tools, materials, ladders, cords, chemicals, and blades before leaving the jobsite.</li>
          <li>Do not discuss pricing disputes, payments, or contract issues directly unless authorized.</li>
          <li>Contact the project manager if a customer requests additional work or changes.</li>
          <li>Document completed work, inspections, material receipts, and jobsite issues daily.</li>
          <li>Leave the property safer, cleaner, and better organized than when work started.</li>
