    // Conflict-proof infinite scroller (no reliance on CSS animations)
    (function(){
      function initLooper(trackId, speedPxPerFrame) {
        const track = document.getElementById(trackId);
        if (!track) return;

        // Clone original set once (so we can loop by half-width)
        const originals = Array.from(track.children);
        originals.forEach(node => track.appendChild(node.cloneNode(true)));

        // If the track is still shorter than the shell, clone again until it's at least 2x shell width
        const shell = track.closest('.scroller-bg');
        function ensureWidth(){
          let guard = 0;
          while (track.scrollWidth < shell.clientWidth * 2 && guard < 8) {
            originals.forEach(node => track.appendChild(node.cloneNode(true)));
            guard++;
          }
        }
        ensureWidth();

        let x = 0;
        function step(){
          x -= speedPxPerFrame;
          // Reset when we've scrolled one full original set
          const resetAt = track.scrollWidth / 2;
          if (Math.abs(x) >= resetAt) x = 0;
          track.style.transform = 'translateX(' + x + 'px)';
          requestAnimationFrame(step);
        }
        requestAnimationFrame(step);
      }

      // Initialize both lines; slightly different speeds
      document.addEventListener('DOMContentLoaded', function(){
        initLooper('track-counties', 1.2);
        initLooper('track-suppliers', 1.6);
      });
    })();
